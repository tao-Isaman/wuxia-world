// Jianghu saga: lone_sword — เก้ากระบี่เดียวดาย (skill `dgjj`, jianghu T4).
//
// More than a hundred and forty years ago a nameless swordsman who "sought
// defeat and never found it" carved nine groups of sword marks into the face
// of the cliff above Huashan (ผาสำนึกผิด, cliff_siguo): nine forms, each
// breaking one kind of weapon, and a ninth group no one can read. In 1401 a
// former copyist of the emptied หอคัมภีร์หลวง — เหวินอี้, who believes an art
// is only safe once it is "collected" — goes about the jianghu as a friendly
// scholar sketching masters' styles, and kills them once the sketch is done.
// He wants the cliff, because the nine forms are the one thing that can break
// every style in his collection. The hero meets the living masters of nine
// weapons, learns the flaw of each, loses friends' trust and wins it back,
// rescues the dreamer หยางซื่อ (a failed Huashan applicant with a notebook of
// 99 defeats) and finds that the ninth form is no form at all.
//
// Theme: เดียวดาย — the swordsman who could not be beaten was alone; the
// collector who owns every style is alone; the hero, who loses to nine
// masters and keeps them all as friends, is not. "ไร้ท่า จึงไม่มีช่อง".
//
