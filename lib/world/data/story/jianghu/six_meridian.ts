// ต้าหลี่, 1401. Three hundred years ago an old monk of the Duan line burned
// the six meridian charts in front of a foreign royal preceptor, and a young
// prince of Dali carried them out in his head. Later he split the teaching
// into six trials, one per meridian, kept by six keeper lines in the temples,
// hills and pools of the south-west — so no thief could take it all, and so
// it could only be learned by a heart that moves for someone else.
//
// Now forged "six meridian" manuals flood the Dali markets and tear the hands
// of the young fools who practise them; a smiling lama-sorcerer from beyond
// the snows, ลามะดอร์เจ, buys every copy, reads it and burns it, and starts
// hunting the keepers. The forger turns out to be the Duan heir himself, who
// printed the fakes to drown the lama in lies — and the hero, passing the
// trials, turns out to be the lamp the lama has been following.
//
// Theme: the sword comes only when the heart moves for another. Six fingers,
// six lessons: breath (เส้าซาง), truth (ซางหยาง), uprightness (จงชง),
// a kept promise (กวนชง), mercy (เส้าชง) and letting go (เส้าเจ๋อ).
