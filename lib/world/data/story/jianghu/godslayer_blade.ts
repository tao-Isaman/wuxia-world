// Jianghu saga: godslayer_blade — ดาบยาวเทพสังหาร (ng5, ยุทธจักร T4).
//
// Fifty years ago, at the Yuan garrison fort that is now the desert ruins,
// the executioner เฉียวดาบเดียว cut off the head of ฮูหลัน, a desert prophet
// who swore no blade could cut a god. Folk called the blade "the god-slayer".
// The executioner never lifted a blade again. When the fort fell to the Ming
// the blade went to the bandit lords of the west, who passed it hand to hand
// — each one killing the last and swearing the blade made him do it.
//
// In 1401 a dying bandit boy brings it to หมู่บ้านไร้นาม, asking for "the
// executioner's daughter" — ยายเฉียว who herds goats. The prophet's son,
// ฮูหลันเจี๋ย, now leads the iron-masked ลัทธิทรายเลือด: he wants the
// thousandth head (the executioner's blood) and sells the rumour that the
// blade can kill a Son of Heaven to both armies of the war.
//
// Theme: the steel is not the curse, the will is. The prophet's last words —
// "cut clean, I'm afraid of pain; I'm no god, tell my son to go home" — were
// the executioner's secret: the god-slaying stroke was an act of mercy.
//
//   Act 1 (ch 1–5)   ห่อผ้าแดง — the boy, the bandit lord, the daughter, the masks.
//   Act 2 (ch 6–11)  ห้ามือ — the blade changes hands; its smith; the trade for a child.
//   Act 3 (ch 12–18) หัวที่หนึ่งพัน — the father's notes, the auction, the full moon.
