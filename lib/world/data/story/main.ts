// fleeing guard reaches the hero two years late, and the trail runs from the
// country manor through the capital, the Beggars, Wudang and Shaolin, the
// burned vault and an empty fort in the north. The hero ends by tearing the
// ledger into pages — each sect gets back only its own — and steps into the
// age of strife (the free game: sects, lineages, sagas).
//
